#!/usr/bin/env python3
"""Check autoregressive source replay against the compiled native readout."""
import argparse
import ctypes
import json
import sys
from pathlib import Path
import torch
from optimizer_state import load_model
from retained_conditioning import evaluate
from train_cuda_trajectories import sha


def verify(root,runtime,probe,out):
    torch.set_num_threads(1);sys.path.insert(0,str(root/'bob3ect/reentry_dnn'))
    from dtransformer_torch import DialetheicTransformerTorch
    build=json.loads((runtime/'build.json').read_text());checkpoint=Path(build['parent'])
    report=json.loads(probe.read_text());assert sha(checkpoint/'model.safetensors')==report['checkpoint_sha256']
    model=DialetheicTransformerTorch(**build['config']).double();model.load_state_dict(load_model(checkpoint/'model.safetensors'))
    library=ctypes.CDLL(str(runtime/'model.so'))
    library.vgi_retained_token.argtypes=[ctypes.c_long]*2;library.vgi_retained_token.restype=ctypes.c_long
    library.vgi_retained_update.argtypes=[ctypes.c_long]*6;library.vgi_retained_update.restype=ctypes.c_long
    library.vgi_retained_first.argtypes=[ctypes.c_long]*2;library.vgi_retained_first.restype=ctypes.c_double
    results=[]
    with torch.no_grad():
        for row in report['results']:
            library.vgi_retained_reset();prefix=[256]+list(row['prompt'].encode())+[257];generated=[];error=0.
            for expected in row['trace'][:16]:
                tokens=prefix+generated
                for i,token in enumerate(tokens+[258]):assert library.vgi_retained_token(i,token)==0
                assert library.vgi_retained_update(len(tokens),1,0,0,0,1)>=0
                actual=evaluate(model,tokens,[258],context=16)
                logits=[]
                for channel in (0,1):
                    native=torch.tensor([library.vgi_retained_first(channel,i) for i in range(model.V)],dtype=torch.double)
                    error=max(error,float((native-actual['first_logits'][channel]).abs().max()));logits.append(native)
                allowed=torch.tensor(list(range(256))+[258]);token=int(allowed[logits[0][allowed].argmax()])
                assert token==expected['token'];generated.append(token)
                if token==258:break
            assert error<1e-8,error
            results.append({'prompt':row['prompt'],'steps':len(generated),'native_logit_error':error,'greedy_bytes_exact':True})
    result={'status':'passed','checkpoint_sha256':report['checkpoint_sha256'],'module_sha256':sha(runtime/'model.imasm'),
        'results':results,'scope':'next-token support and refutation match the native retained learner over prompt replay and successive generated bytes; no updates'}
    out.write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result))


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ('root','runtime','probe','out'):p.add_argument('--'+name,type=Path,required=True)
    a=p.parse_args();verify(*(getattr(a,name).resolve() for name in ('root','runtime','probe','out')))
